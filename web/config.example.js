/* ============================================================
 *  配置示例 —— 复制成 config.js 再填你自己的值
 *
 *  为什么单独一个文件：因为这里装的是密钥和地址，
 *  它们不该出现在代码里，更不该被提交到公开仓库。
 *  config.js 已经在 .gitignore 里，提交不上去。
 *
 *  ── 怎么用 ──
 *  1. 复制本文件：  cp config.example.js config.js
 *  2. 填上你的总线地址、主题名、口令
 *  3. 打开 index.html 即可
 * ============================================================ */
window.GROUP_CONFIG = {

  /* 消息总线的地址。
     用公共 ntfy（试用最快）：  "https://ntfy.sh"
     自建（推荐，随便选个）：    "https://你的域名"  或  "http://192.168.1.10:8080" */
  base: "https://ntfy.sh",

  /* 出站主题：机器人/设备 -> 群（它们说什么，群里就显示什么）
     主题名自己随便起一个够长的随机串，起完别告诉外人 */
  topic: "换成你自己的主题名",

  /* 入站主题：群 -> 机器人（你在输入框里打的话，经这里发给它们）
     留空就表示入站和出站共用一个主题 */
  inTopic: "",

  /* 口令：只有带这个口令的消息才会唤醒 agent。
     为什么必须有：总线默认是公开的，没有口令等于把命令执行权挂网上。
     想省事可以把 inTopic 和这里一起留空，但那只能用在内网/自己的机器上。 */
  token: "",

  /* 可选 —— 手机排查视口问题用的体检通道，不用就删掉这行 */
  diag: ""

};
